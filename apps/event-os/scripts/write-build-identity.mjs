#!/usr/bin/env node
/**
 * Embed immutable Event OS application identity at build time.
 * Priority: RAILWAY_GIT_COMMIT_SHA → EVENT_OS_GIT_SHA → git rev-parse HEAD → local-unreleased
 * Runtime must prefer this embedded value so a stale service env cannot override.
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const FULL_SHA = /^[a-f0-9]{40}$/i;

function readGitHead() {
  try {
    return execSync("git rev-parse HEAD", { encoding: "utf8" }).trim();
  } catch {
    return undefined;
  }
}

function resolveSha() {
  const candidates = [
    process.env.RAILWAY_GIT_COMMIT_SHA,
    process.env.EVENT_OS_GIT_SHA,
    readGitHead(),
  ];
  for (const value of candidates) {
    const trimmed = value?.trim();
    if (trimmed && FULL_SHA.test(trimmed)) return trimmed.toLowerCase();
  }
  return "local-unreleased";
}

const sha = resolveSha();
const source =
  process.env.RAILWAY_GIT_COMMIT_SHA && FULL_SHA.test(process.env.RAILWAY_GIT_COMMIT_SHA.trim())
    ? "RAILWAY_GIT_COMMIT_SHA"
    : process.env.EVENT_OS_GIT_SHA && FULL_SHA.test(process.env.EVENT_OS_GIT_SHA.trim())
      ? "EVENT_OS_GIT_SHA"
      : sha === "local-unreleased"
        ? "LOCAL_FALLBACK"
        : "GIT_REV_PARSE";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "server", "build-identity.generated.ts");
writeFileSync(
  out,
  `/* Generated by scripts/write-build-identity.mjs — do not edit by hand. */\n` +
    `export const BUILD_APPLICATION_SHA = ${JSON.stringify(sha)} as const;\n` +
    `export const BUILD_IDENTITY_SOURCE = ${JSON.stringify(source)} as const;\n` +
    `export const BUILD_IDENTITY_CAPTURED_AT = ${JSON.stringify(new Date().toISOString())} as const;\n`,
);
console.log(`[event-os] build identity ${sha} (source=${source})`);
